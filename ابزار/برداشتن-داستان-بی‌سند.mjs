/**
 * برداشتنِ داستانِ بی‌سند از راهنمای شروع
 *
 * ⭐ چرا این کار؟
 *
 * راهنمای شروع این داستان را داشت: «سال ۱۹۳۰، دانشجویی که ۳۰۰ صفحه دربارهٔ
 * موجیت خواند». این همان روایتی است که سال‌ها در کتاب‌های بازارِ تکنولوژی
 * تکرار می‌شود و معمولاً به «هرمن هیدرن» نسبت داده می‌شود — که سندِ مستندی
 * ندارد.
 *
 * برای جایگزینی، روایتِ «مدرسهٔ کیش با پروژهٔ جزیره» نوشته شد. راستی‌آزمایی
 * کردیم و نتیجه این بود: **هیچ سندی وجود ندارد** — نه مقالهٔ داوری‌شده، نه
 * گزارشِ وزارت‌آموزش، نه خبر. تنها یک نقلِ شفاهیِ بی‌منبع است.
 *
 * پس جایگزین هم ساختگی بود. حذف کردنِ داستان، از نوشتنِ داستانِ دیگری
 * صادقانه‌تر است — و بخشِ بعدی همان حرف را با سند می‌زند.
 *
 * دربارهٔ بخشِ 🧒: استانداردِ نگارش آن را برای فازها الزامی کرده، ولی
 * راهنما یک فاز نیست و اینجا داستان جای خود را به «چرا این بخش هست»
 * می‌دهد.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const path = join(here, '..', 'فازها', '۰۰-راهنمای-شروع.md')

const OLD = [
  '> 🧒 **داستان این بخش:** سال ۱۹۳۰، یک دانشجو کتابی درباره‌ی «موجیت» در فیزیک',
  '> باز کرد. تمام ۳۰۰ صفحه را خواند. فردا از او پرسیدند «موجیت چیست؟» و جواب',
  '> نداد. روز بعد، همان دانشجو فقط فصلِ موجیت را خواند و یک تمرین حل کرد. این بار',
  '> جواب داد.',
  '>',
  '> اسمش **هرمن رایشوِ هیدرن** نبود؛ در واقع این روایت را به اسم کسی نسبت',
  '> نمی‌دهیم، چون سندِ محکمی برایش نیست. ولی اصلِ حرفش این است که خواندنِ',
  '> یک‌باره فرق دارد با **درگیر شدن** با متن.',
  '>',
  '> **این بخش جواب می‌دهد:** چطور بخوانم، و داستانِ 🧒 و فلش‌کارت هر کدام چه',
  '> چیزی به من می‌دهند.',
].join('\n')

const NEW = [
  '> **این بخش جواب می‌دهد:** چطور بخوانم، و داستانِ 🧒 و فلش‌کارت هر کدام چه',
  '> چیزی به من می‌دهند. اگر وقتت کم است، فقط پاراگرافِ بعدی را بخوان و بقیهٔ',
  '> فهرست را رد کن.',
].join('\n')

let text = readFileSync(path, 'utf8')

if (text.includes(NEW)) {
  console.log('✓ قبلاً برداشته شده — دست نمی‌زنم')
} else if (!text.includes(OLD)) {
  console.log('✗ داستان پیدا نشد — دست نمی‌زنم')
  process.exitCode = 1
} else {
  text = text.replace(OLD, NEW)
  writeFileSync(path, text, 'utf8')
  console.log('✓ داستانِ بی‌سند برداشته شد')
}