/**
 * ثبتِ قاعدهٔ «هر DOI را خودت باز کن» در استاندارد نگارش
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const path = join(here, '..', 'محتوا', 'استاندارد-نگارش.md')

let text = readFileSync(path, 'utf8')

// ── ۱) بلافاصله بعد از قاعدهٔ ادعای بی‌سند ──
const ANCHOR = '## اشتباه‌های رایجی که باید رفع شوند'
const RULE = [
  '## ⭐ هر شناسه را خودت باز کن — ابزار شاهد نیست',
  '',
  'در همین پروژه یک ارجاعِ ساختگی از ابزار جست‌وجوی وب بیرون آمد: مقاله‌ای',
  'با نامِ دقیقِ همان کسی که دنبالش بودیم، با سالِ دقیقِ فرض‌شده، و **فرمولِ',
  'همراهش** — طوری که انگار از متنِ مقاله برآمده بود.',
  '',
  'همان DOI را که باز کردیم:',
  '',
  '```',
  'ادعا:  Donald R. Farquhar, Psych. Review 57(1), 1950, DOI 10.1037/h0057982',
  'واقعی: Stainbrook & Löwenbach — رفتار موش در هزاره،',
  '         J. Comparative Psychology 34(3), ۱۹۴۲',
  '```',
  '',
  'پس سه قانون برای هر ارجاعی که از جست‌وجو می‌آید:',
  '',
  '1. **DOI، RFC، یا شمارهٔ کتاب را خودت باز کن.** نتیجهٔ جست‌وجو',
  '   «شاهد» نیست؛ فقط نشانی است.',
  '2. **اگر باز نشد، ننویس.** بنویس «تأییدنشده» — که برای خوانندهٔ',
  '   آفلاین، خیلی مفیدتر از یک ارجاعِ ساختگی است.',
  '3. ⚠️ **اگر فرمولی همراهِ ارجاع آمد، قرمزترین حالت است.** فرمول باید از',
  '   متنِ منبع بیاید، نه از بازگویی. فرمولی که خودت هم ندیده‌ای، ننویس.',
  '',
  'جزئیات و نشانی‌ها: [ابزار/یادداشت-ابزار-جست‌وجو-غلط.md](ابزار/یادداشت-ابزار-جست‌وجو-غلط.md)',
  '',
].join('\n')

if (text.includes(ANCHOR) && !text.includes('هر شناسه را خودت باز کن')) {
  text = text.replace(ANCHOR, RULE + ANCHOR)
  console.log('✓ قاعدهٔ «باز کردنِ شناسه» اضافه شد')
} else {
  console.log('· قاعده از قبل هست')
}

writeFileSync(path, text, 'utf8')