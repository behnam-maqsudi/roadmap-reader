import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const path = join(here, '..', 'محتوا', 'استاندارد-نگارش.md')

let text = readFileSync(path, 'utf8')

/** جایگزینی؛ اگر از قبل هست، دست نمی‌زنیم. */
function swap(anchor, next, label) {
  if (!text.includes(anchor)) {
    console.log('✗ لنگر پیدا نشد:', label)
    process.exitCode = 1
    return
  }
  if (text.includes(next)) {
    console.log('✓ قبلاً اضافه شده —', label)
    return
  }
  text = text.replace(anchor, anchor + next)
  console.log('✓ اضافه شد —', label)
}

