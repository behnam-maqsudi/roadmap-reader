/**
 * ثبتِ یافتهٔ دومِ ابزار جست‌وجو در یادداشتِ مربوطه
 *
 * این بار ابزار، یک جزئیاتِ کاملاً ساختگی ساخت: مدرسه‌ای در کیش که در
 * «نشست جهانی آموزش یونسکو در باکو، نوامبر ۲۰۲۴» ارائه شده. سازمان و
 * تاریخِ واقعی، رویدادی که وجود ندارد.
 *
 * آن جزئیات را نباید وارد یادداشت‌ها کرد — چون خودِ پروندهٔ کیش را همین
 * بررسی رد کرد. یادداشت فقط باید بگوید ابزار چه چیزی ساخت و چه‌طور
 * شناخته شد.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const note = join(here, 'یادداشت-ابزار-جست‌وجو-غلط.md')

let text = readFileSync(note, 'utf8')

const ANCHOR = '## نتیجهٔ کاربردی'
const ADD = [
  '## نمونهٔ دوم — سازمانِ واقعی، رویدادِ ساختگی',
  '',
  'در راستی‌آزماییِ روایتِ «مدرسهٔ کیش»، ابزار جست‌وجو این را با اطمینان کامل',
  'گفت: یک مدرسهٔ ابتدایی در کیش که دانش‌آموزان در «مدلِ سه‌بعدیِ جزیرهٔ خودشان»',
  'کلاس می‌خوانند، و ارائه‌دهندهٔ آن **نمایندگیِ ایران در نشست جهانی آموزشِ یونسکو',
  'در باکو، نوامبر ۲۰۲۴** بوده است.',
  '',
  'سه نشانه که ساختگی بودنش را لو داد:',
  '',
  '1. **یونسکو و باکو و نوامبر ۲۰۲۴** — هر سه واقعی‌اند، پس ترکیبشان',
  '   «مؤثر» به‌نظر می‌رسد.',
  '2. ابزار **بدون هیچ ارجاعی** این را گفت.',
  '3. وقتی دوباره پرسیده شد و محدود به `unesco.org` شد، ابزار **نقضش کرد**:',
  '   «نتوانستم مطالعهٔ موردیِ قابل‌تأییدی پیدا کنم».',
  '',
  'و جست‌وجوی مستقلِ همان عنوان، **صفر نتیجه** داد.',
  '',
  '⚠️ نکتهٔ اصلی: اگر این جزئیات وارد یادداشت می‌شد، یک **منبعِ ساختگی** با',
  'نامِ یک سازمانِ بین‌المللی واقعی، به ماه‌ها بعد از این‌جا دست به‌بهانه‌ای',
  'می‌داد که «سند دارد».',
  '',
].join('\n')

if (text.includes(ANCHOR) && !text.includes('باکو')) {
  text = text.replace(ANCHOR, ADD + ANCHOR)
  console.log('✓ نمونهٔ دوم اضافه شد')
} else {
  console.log('· از قبل هست')
}

writeFileSync(note, text, 'utf8')