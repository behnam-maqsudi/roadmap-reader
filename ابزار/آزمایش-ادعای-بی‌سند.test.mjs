/**
 * آزمایش-ادعای-بی‌سند.test.mjs — آیا متن، تاریخ و اسمِ ساختگی می‌گوید؟
 *
 * ⭐ چرا این تست هست؟
 *
 * دو گزارشِ راستی‌آزمایی روی این متن انجام شد و هر دو یک الگوی تکراری
 * نشان دادند: **اسم و کتاب و سالی که در هیچ مرجعی نیست.**
 *
 *   · «Barry J. Farquhar» — در Crossref و OpenAlex و LoC چنین کسی نیست
 *   · داستانِ «دانشجوی ۱۹۳۰ که ۳۰۰ صفحه دربارهٔ موجیت خواند» — سندی ندارد
 *
 * متنِ ما در موردِ دوم خودش نوشته بود «به کسی نمی‌دهیمش» — که کافی نبود،
 * چون **سال و تعداد صفحه** همچنان قطعی روایت شده بود.
 *
 * این تست فهرستِ اسم‌ها و عددهایی را نگه می‌دارد که راستی‌آزمایی رد کرده،
 * تا کسی دوباره واردشان نکند. و یک قاعدهٔ عمومی می‌گذارد: هر تاریخِ
 * همراهِ یک ادعای دقیق باید یا سند داشته باشد، یا خودش را بی‌سند علامت بزند.
 */

import { describe, it } from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync, readdirSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const root = join(here, '..')
const phasesDir = join(root, 'فازها')

/** همه‌ی متن‌های درسی، یک‌جا. */
const allText = readdirSync(phasesDir)
  .filter((f) => f.endsWith('.md'))
  .map((f) => ({ file: f, text: readFileSync(join(phasesDir, f), 'utf8') }))

/**
 * ⭐ چیزهایی که راستی‌آزمایی رد کرده و هرگز نباید وارد متن شوند.
 *
 * هر ردیف: [رشته، چرا]. رشته‌ها عیناً همان چیزی است که در گزارش آمده بود.
 */
const BANNED = [
  [
    'Farquhar',
    'روان‌شناسِ ادعاشده وجود ندارد — Crossref، OpenAlex و LoC هر سه ساکت‌اند',
  ],
  [
    'هایدرن',
    'داستانِ «دانشجو و موجیت» معمولاً به هیدرن نسبت داده می‌شود و سندِ محکمی ندارد',
  ],
  ['موجیت', 'همان داستانِ بی‌سند، در قالبِ فارسی'],
  [
    'Transmission Control Program',
    'عنوانِ غلطِ RFC 793 — عنوانِ درست «Protocol» است و مالِ RFC 675 است',
  ],
  [
    'Paxson',
    'همکارِ ساختگیِ مقالهٔ Jacobson ۱۹۸۸ — آن مقاله تنها نویسنده دارد',
  ],
  // ⭐ ارجاع‌هایی که چهار راستی‌آزماییِ جداگانه رد کردند. هیچ‌کدام در متن
  // نبودند، ولی در گردش‌اند و هر بار که کسی سراغشان برود، دوباره می‌آیند.
  [
    'Keppel',
    'مقالهٔ «کپل و آندرسون ۱۹۵۹» وجود ندارد — فهرستِ کاملِ JEP آن سال آن را ندارد',
  ],
  [
    'Jelberman',
    'هیچ ردّ bibliografیک ندارد — در Crossref و OpenAlex صفر نتیجه',
  ],
  [
    'sleeping over',
    'مقالهٔ لوftوس ۱۹۷۹ وجود ندارد — مقالهٔ واقعی دربارهٔ weapon focus است',
  ],
]

describe('ادعاهای بی‌سند نباید وارد متن شوند', () => {
  for (const [needle, why] of BANNED) {
    it(`«${needle}» در هیچ فازی نیست`, () => {
      const hits = allText
        .filter(({ text }) => text.includes(needle))
        .map(({ file }) => file)

      assert.deepEqual(hits, [], `${needle} پیدا شد در ${hits.join('، ')} — ${why}`)
    })
  }
})

describe('داستانِ بی‌سند، خودش را علامت می‌زند', () => {
  it('هر روایتِ ساختگی، یا سند دارد یا خودش را بی‌سند می‌گوید', () => {
    // داستان‌های 🧒 با جمله‌هایی شروع می‌شوند که زمان و آدم را ادعا می‌کنند.
    // الگوی نگران‌کننده: یک سالِ دقیق + یک عددِ دقیق، بدون هیچ ارجاعی.
    const SUSPECT = /\*\*داستان این بخش:\*\*[^\n]*\b(سال|در سال)\s*[۱۳][۰-۹۰-۹]{3}/

    for (const { file, text } of allText) {
      const lines = text.split('\n')
      for (let i = 0; i < lines.length; i += 1) {
        if (!SUSPECT.test(lines[i])) continue

        // یک یا دو خط بالاتر و پایین‌تر، پاراگرافِ داستان است
        const block = lines.slice(i, i + 12).join('\n')
        const disclaims = /سندِ|بدون سند|نمی‌دهیم|روایتِ|شایع|منتسب|واقعی نیست/

        assert.ok(
          disclaims.test(block),
          `${file}:${i + 1} داستان سالِ دقیق می‌دهد ولی نه سند دارد، ` +
            `نه خودش را بی‌سند علامت می‌زند`,
        )
      }
    }
  })
})

describe('هر تاریخِ دقیق، منبع دارد', () => {
  it('هر فازی که سال می‌آورد، بخشِ «منابع» هم دارد', () => {
    // این تست عمداً سخت‌گیر نیست: بررسی می‌کند که هر فازی که سالِ مشخص
    // می‌آورد، بخشِ «منابع» هم داشته باشد. فازهایی که سال نمی‌آورند exempt‌اند.
    //
    // ⚠️ راهنمای شروع استثناست: فاز نیست و ارجاع به فازهای دیگر می‌دهد،
    // پس ساختارِ «منابع» ندارد و نباید هم داشته باشد.
    const isGuide = (file) => file.includes('راهنما')

    for (const { file, text } of allText) {
      if (isGuide(file)) continue

      const hasYear = /(?:سال\s*[۰-۹]{4}|[۱۳][۰-۹]{2})/.test(text)
      if (!hasYear) continue

      assert.match(
        text,
        /##\s*[^\n]*منابع/,
        `${file} سال می‌آورد ولی بخشِ «منابع» ندارد — سندی برای تاریخ‌ها نیست`,
      )
    }
  })
})