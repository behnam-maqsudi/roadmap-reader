/**
 * ثبتِ قاعدهٔ «ادعای بی‌سند» در استاندارد نگارش
 *
 * از دو راستی‌آزماییِ واقعی بیرون آمد. مهم‌ترین قاعدهٔ تازه: **«به کسی
 * نمی‌دهیمش» کافی نیست** — اگر سال و عدد نوشته‌ای، خودِ آن جزئیات هم ادعای
 * تاریخی‌اند.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'

const here = dirname(fileURLToPath(import.meta.url))
const path = join(here, '..', 'محتوا', 'استاندارد-نگارش.md')

let text = readFileSync(path, 'utf8')

// ── ۱) ردیفِ نهمِ جدولِ تست‌ها ──
const ROW = '| `آزمایش-تایپ-واقعی` |'
if (text.includes(ROW) && !text.includes('آزمایش-ادعای-بی‌سند')) {
  const at = text.indexOf(ROW)
  const end = text.indexOf('\n', at) + 1
  text =
    text.slice(0, end) +
    '| `آزمایش-ادعای-بی‌سند` | اسم و کتابِ ردشده وارد متن نمی‌شود؛ داستانِ بی‌سند خودش را علامت می‌زند |\n' +
    text.slice(end)
  console.log('✓ ردیفِ ادعای بی‌سند اضافه شد')
}

if (text.includes('### هشت تستِ ساختاری')) {
  text = text.replace('### هشت تستِ ساختاری', '### نه تستِ ساختاری')
  console.log('✓ تیتر به «نه تست» تغییر کرد')
}

// ── ۲) قاعدهٔ تازه، کنار بقیهٔ اشتباه‌های رایج ──
const ANCHOR = '## اشتباه‌های رایجی که باید رفع شوند'
const RULE = [
  '## ⭐ ادعای بی‌سند — «به کسی نمی‌دهیمش» کافی نیست',
  '',
  'دو راستی‌آزماییِ واقعی روی این متن انجام شد و هر دو یک الگوی تکراری',
  'نشان دادند: **اسم، کتاب یا سالی که در هیچ مرجعی نیست.**',
  '',
  'یک نمونهٔ واقعی از متنِ خودمان: راهنمای شروع داستانِ «دانشجویی که سال',
  '۱۹۳۰ سیصد صفحه دربارهٔ موجیت خواند» را داشت. متن نوشته بود «این روایت',
  'را به اسم کسی نسبت نمی‌دهیم» — که **درست بود ولی کافی نبود**، چون سال و',
  'تعدادِ صفحه همچنان قطعی روایت شده بودند.',
  '',
  'پس سه قانون:',
  '',
  '1. **عدد و سال، ادعا هستند.** «سیصد صفحه» و «سال ۱۹۳۰» به‌اندازهٔ خودِ',
  '   اسم، نیاز به سند دارند.',
  '2. یا **سند بده** (بخشِ `منابع`)، یا خودت را **بی‌سند علامت بزن** — با',
  '   واژه‌ای مثل «سندِ محکمی ندارد» یا «روایتِ شایعی است».',
  '3. ❌ **راویِ بی‌نام ممنوع نیست، راویِ ساختگی ممنوع است.** نوشتنِ «یک',
  '   نفر در فلان سال» به‌جای «فلان آدم در فلان سال» فقط تردید را پنهان',
  '   می‌کند، در حالی که همان جزئیات را ادعا کرده‌ای.',
  '',
  '`آزمایش-ادعای-بی‌سند` این را نگه می‌دارد: فهرستِ اسم‌های ردشده هرگز',
  'برنمی‌گردند، و هر داستانِ دارایِ سالِ دقیق باید یا منبع داشته باشد یا',
  'خودش را بی‌سند علامت بزند.',
  '',
].join('\n')

if (text.includes(ANCHOR) && !text.includes('ادعای بی‌سند')) {
  text = text.replace(ANCHOR, RULE + ANCHOR)
  console.log('✓ قاعدهٔ ادعای بی‌سند اضافه شد')
}

writeFileSync(path, text, 'utf8')