/**
 * slug.js — ساخت شناسه‌ی لنگر برای سرتیترها
 *
 * ⭐ چرا فایل جدا؟
 *
 * فهرستِ کنار صفحه (`App.tsx`) و رندرر (`Markdown.tsx`) هر دو باید **دقیقاً**
 * یک شناسه برای یک سرتیتر بسازند. اگر منطقشان دو جا باشد، یک روز یکی
 * عوض می‌شود و کلیک روی فهرست بی‌صدا از کار می‌افتد — دقیقاً همان باگی که
 * برای کاربر پیش آمد. برای همین قاعده‌ی شماره‌گذاری اینجا یک بار نوشته
 * شده و هر دو از همین می‌خوانند.
 *
 * ⭐ چرا `.js` و نه `.ts`؟
 * چون تستِ `ابزار/آزمایش-لنگر.test.mjs` هم باید همین کد را اجرا کند تا
 * مطمئن شود فهرست و رندر یکی می‌سازند. `node --test` فایل TypeScript را
 * نمی‌خواند. نوع‌ها در `slug.d.ts` تعریف شده‌اند، پس TypeScript همچنان
 * همه‌چیز را type-safe می‌بیند.
 */

/** تبدیل عنوان به شناسه، مثل GitHub. */
export function slugify(text) {
  return text
    .trim()
    .toLowerCase()
    .replace(/[^\p{L}\p{N}\s-]/gu, '')
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-')
}

/** نامِ پایه‌ی یک سرتیتر؛ اگر خالی شد، «بخش» می‌شود. */
function baseSlug(text) {
  return slugify(text) || 'بخش'
}

/**
 * ⭐ یک گام از شماره‌گذاریِ تکراری‌ها.
 *
 * دو سرتیتر می‌توانند متن یکسان داشته باشند (مثلاً «منابع» در چند بخش). اگر
 * هر دو `id` یکسان بگیرند، لنگرِ دومی کار نمی‌کند چون مرورگر اولی را پیدا
 * می‌کند. پس هر تکرار یک پسوند شماره‌ای می‌گیرد.
 *
 * شمارنده در `seen` نگه داشته می‌شود و **بین فراخوانی‌ها زنده می‌ماند**، پس
 * رندرر می‌تواند سرتیترها را یکی‌یکی بسازد و همان قاعده را رعایت کند.
 *
 * @param {Map<string, number>} seen شمارنده‌ی همان سند
 * @returns {string} شناسه‌ی یکتا
 */
export function nextSlug(text, seen) {
  const base = baseSlug(text)
  // شمارنده = شمارِ سرتیترهایی که تا اینجا این پایه را گرفته‌اند.
  // اولی ۰ است و بدون پسوند می‌ماند؛ دومی ۱ می‌شود و «-1» می‌گیرد.
  const count = seen.get(base) ?? 0
  seen.set(base, count + 1)
  return count === 0 ? base : `${base}-${count}`
}

/**
 * شناسه‌های یکتا برای فهرستی از سرتیترها.
 *
 * همان قاعده‌ی `nextSlug`، ولی برای وقتی که همه‌ی سرتیترها از قبل معلوم‌اند
 * (مثل فهرستِ کنار صفحه که از روی متن ساخته می‌شود).
 *
 * @param {string[]} headings متنِ سرتیترها، به همان ترتیبی که در سند آمده‌اند
 * @returns {string[]} شناسه‌ی یکتا برای هر کدام، هم‌ترتیب با ورودی
 */
export function buildSlugs(headings) {
  const seen = new Map()
  return headings.map((text) => nextSlug(text, seen))
}

/**
 * ⭐ تنها جایی که سرتیترهای یک سند از متن درمی‌آیند.
 *
 * هر دو مصرف‌کننده — فهرستِ کنارِ صفحه (`App.tsx`) و رندرر
 * (`Markdown.tsx`) — از **همین** تابع می‌خوانند. برای همین است که هیچ‌وقت
 * نمی‌توانند از هم جدا بیفتند: نه با یک نسخه‌ی قدیمی، نه با یک باگِ
 * ناخواسته.
 *
 * ⭐⭐ چرا `line` برمی‌گرداند؟
 *
 * رندرر باید بداند «این سرتیترِ خاص» کدام است. متنش به‌تنهایی کافی نیست،
 * چون متن تکراری است: «چرا وجود دارد؟» در یک فاز پنج بار می‌آید و هرکدام
 * `id` متفاوتی می‌گیرند.
 *
 * جای‌گزینِ شمارندهٔ مشترک (که باید در حین رندر تغییر کند و در
 * `StrictMode` دوبار شمرده می‌شد) **شمارهٔ سطر** است: react-markdown
 * موقعیتِ هر سرتیتر را در متنِ اصلی می‌دهد و این موقعیت در هر رندری
 * **دقیقاً یکی** است. پس نگاشتِ «سطر ← شناسه» یک جدولِ ثابت است، نه
 * چیزی که موقع رندر محاسبه شود.
 *
 * @param {string} markdown متنِ کاملِ سند
 * @returns {{text: string, level: number, line: number, id: string}[]}
 */
export function extractHeadings(markdown) {
  const found = []
  let inFence = false
  const lines = markdown.split('\n')

  for (let i = 0; i < lines.length; i++) {
    const line = lines[i]

    // داخلِ بلوکِ کد، `#` سرتیتر نیست — نشانهٔ کامنت است.
    if (/^\s*(```|~~~)/.test(line)) {
      inFence = !inFence
      continue
    }
    if (inFence) continue

    const m = line.match(/^(#{1,6})\s+(.+?)\s*#*\s*$/)
    if (!m) continue

    found.push({
      text: m[2].trim(),
      level: m[1].length,
      line: i + 1, // react-markdown سطر را از ۱ می‌شمارد
    })
  }

  // شناسه‌ها را **فقط برای همان سرتیترهایی** می‌سازیم که فهرست هم می‌بیند.
  // `App.tsx` سطحِ ۱ تا ۳ را نشان می‌دهد، ولی شمارشِ تکراری‌ها باید روی
  // *همهٔ* سرتیترها باشد تا شماره‌ها بین دو مسیر یکی بمانند.
  const ids = buildSlugs(found.map((h) => h.text))
  return found.map((h, i) => ({ ...h, id: ids[i] }))
}
