/**
 * callout.ts — تبدیلِ نقل‌قول‌های ایموجی‌دار به کارت‌های آموزشی
 *
 * ⭐⭐ چرا این فایل مهم است
 *
 * در متنِ درس، ایموجی‌هایی مثل 🧒 و 💡 و 🔑 و ⚠️ **دویست‌بار** آمده‌اند،
 * ولی در نسخهٔ ۱ هیچ استایلی نداشتند: همه‌شان مثل یک نقل‌قولِ خاکستریِ
 * معمولی درمی‌آمدند. خواننده نمی‌توانست فرقِ «نکته» و «هشدار» و
 * «اشتباه مرگبار» را **بی‌درنگ** ببیند — و این دقیقاً همان چیزی است که
 * متن را خشک می‌کرد.
 *
 * اینجا هر ایموجی رنگ، کادر و تیترِ خودش را می‌گیرد.
 *
 * ── الگوی متن ──
 * در فایل‌های `فازها/*.md` این‌طور نوشته شده:
 *
 *     > 🧒 **داستان این بخش:** سال ۱۹۶۹، شرکت بل‌لبز…
 *     > متنِ ادامه در خطِ بعد
 *     >
 *     > **این بخش جواب می‌دهد:** …
 *
 * یعنی ایموجی اولِ بلاک، کلیدِ نوع است و تیتر داخلِ `**…:**` می‌آید.
 */

/** نوعِ کارت — هر کدام رنگ و رفتارِ خودش را دارد. */
export type CalloutKind =
  | 'story'
  | 'note'
  | 'key'
  | 'warn'
  | 'danger'
  | 'trap'
  | 'ok'
  | 'bad'
  | 'goal'
  | 'link'
  | 'read'
  | 'plain'

export interface CalloutSpec {
  kind: CalloutKind
  /** تیترِ پیش‌فرض، وقتی متن تیترِ خودش را ندارد */
  label: string
}

/**
 * ⭐⭐ جدولِ نگاشتِ ایموجی به نوعِ کارت.
 *
 * این جدول از روی **خودِ محتوا** درآمده، نه حدس. یک اسکریپتِ موقت همهٔ
 * `>`‑های ابتدای خط را شمرد و این ایموجی‌ها را به‌دست آورد:
 *
 *   🧒 ۱۷۴ · 💡 ~۱۰۰ · 🔑 ~۹۰ · ⚠️ ~۳۰ · 📌 ۸ · 🔴 ۵ · ⛔ ۱ · 📖 ۳ · ❌ ۱
 *
 * یعنی این جدول **همهٔ** ایموجی‌های واقعیِ متن را پوشش می‌دهد، نه چندتای
 * دلخواه. اگر فردا ایموجی تازه‌ای اضافه شد، `plain` می‌گیرد و صفحه
 * نمی‌شکند.
 */
const EMOJI_MAP: Record<string, CalloutSpec> = {
  '🧒': { kind: 'story', label: 'داستان' },
  '💡': { kind: 'note', label: 'نکته' },
  '🔑': { kind: 'key', label: 'قاعدهٔ کلیدی' },
  '⚠️': { kind: 'warn', label: 'هشدار' },
  '🔴': { kind: 'danger', label: 'خطر' },
  '⛔': { kind: 'trap', label: 'دامِ رایج' },
  '✅': { kind: 'ok', label: 'درست' },
  '❌': { kind: 'bad', label: 'نادرست' },
  '🎯': { kind: 'goal', label: 'هدف' },
  '📌': { kind: 'link', label: 'پیوند' },
  '📖': { kind: 'read', label: 'مطالعه' },
  '⚡': { kind: 'note', label: 'نکتهٔ سریع' },
  '🧪': { kind: 'note', label: 'آزمایش' },
  '🔍': { kind: 'note', label: 'بررسی' },
}

/** ایموجیِ اولِ یک خط نقل‌قول — همان کلیدِ نوع. */
const LEAD_EMOJI =
  /^[\s>]*([\u{1F300}-\u{1FAFF}\u{2600}-\u{27BF}\u{2B00}-\u{2BFF}\u{1F000}-\u{1F0FF}][\u{FE0F}\u{20E3}]?)\s*/u

/**
 * ⭐ آیا این بلاک، کارتِ آموزشی است؟
 *
 * پارامتر `text` متنِ قابل‌مشاهدهٔ فرزندانِ `blockquote` است (نه HTML خام).
 * اگر با ایموجیِ شناخته‌شده شروع شود، کارت است؛ وگرنه نقل‌قولِ معمولی و
 * با ظاهرِ عادی رندر می‌شود.
 */
export function detectCallout(text: string): CalloutSpec | null {
  const trimmed = text.trimStart()
  const m = trimmed.match(LEAD_EMOJI)
  if (!m) return null

  // بعضی ایموجی‌ها با «موجودیتِ تغییرپذیر» (ZWJ) یا چند کدپوینت می‌آیند.
  // پس کلِ رشتهٔ ایموجی را با جدول مقایسه می‌کنیم، نه تک‌کدپوینتِ اول.
  const afterEmoji = trimmed.slice(m[0].length)
  const probe = `${m[1]}${afterEmoji.match(/^[\u{FE0F}\u{20E3}\u{200D}‍\u{1F3FB}-\u{1F3FF}]*/u)?.[0] ?? ''}`

  const spec = EMOJI_MAP[probe] ?? EMOJI_MAP[m[1]]
  return spec ?? null
}

/**
 * ⭐ جدا کردنِ تیتر از بدنه.
 *
 * متنِ درس تیتر را این‌طور می‌نویسد: `**داستان این بخش:** متن…`
 * یعنی تیتر داخلِ `**` است و بعدش colon. اگر چنین الگویی در ۳۰ نویسهٔ اول
 * باشد، آن را جدا می‌کنیم و به‌عنوان تیترِ کارت می‌گذاریم.
 *
 * ⚠️ چرا فقطِ اولین خط و فقطِ اگر بلافاصله بعد از ایموجی باشد؟
 * چون متنِ درس پر از عبارت‌هایی مثل «**پاسخ:** …» در وسطِ پاراگراف است
 * و اگر هر `**…:**` را تیتر می‌گرفتیم، نیمی از کارت‌ها تیترِ بی‌معنا
 * می‌گرفتند. محدودکردنش به ابتدای کارت، دقت را بالا نگه می‌دارد.
 */
export function splitTitle(body: string): { title: string | null; rest: string } {
  const firstLineEnd = body.indexOf('\n')
  const firstLine = firstLineEnd === -1 ? body : body.slice(0, firstLineEnd)

  const m = firstLine.match(/^\s*\*\*(.{1,60}?)\*\*\s*[:：]\s*(.*)$/u)
  if (!m) return { title: null, rest: body }

  const title = m[1].trim()
  const remainder = m[2].trim()
  const tail = firstLineEnd === -1 ? '' : body.slice(firstLineEnd)

  // اگر بعد از تیتر چیزی نمانده، تیترِ تنها نمانده باشد
  const rest = (remainder + tail).trimStart()
  return { title, rest }
}