import type { Doc } from '../types'

export type { Doc }

/** انواعِ پرسشِ تعاملی که در نسخهٔ ۲ اضافه شده. */
export type QuestionKind = 'choice' | 'predict' | 'exercise'

/** یک گزینه در پرسشِ چندگزینه‌ای.
 *
 *  ⭐ `why` مهم‌ترین بخشِ این ساختار است. اگر کاربر گزینهٔ غلط را بزند،
 *  باید **دقیقاً همان اشتباهِ او** را توضیح بدهد، نه اینکه فقط بگوید
 *  «غلط است». این همان چیزی است که پرسش را از آزمون به «درس» تبدیل می‌کند. */
export interface Choice {
  /** متنِ گزینه (می‌تواند کد یا عبارت لاتین باشد) */
  text: string
  /** چرا این گزینه درست است یا اگر غلط، *چه* اشتباهی را نشان می‌دهد */
  why: string
}

export interface BaseQuestion {
  /** شناسهٔ پایدار، برای ذخیرهٔ پاسخ کاربر */
  id: string
  /** تیتر کوتاهی که بالای پرسش می‌آید */
  title: string
  /** توضیحِ مسئله پیش از پرسش */
  prompt: string
  /** شمارهٔ بخشِ درسی که این پرسش از آن آمده (برای ناوبری) */
  section?: string
}

export interface ChoiceQuestion extends BaseQuestion {
  kind: 'choice'
  question: string
  options: Choice[]
  /** اندیسِ گزینهٔ درست. عمداً به‌جای `correct: string`، چون
   *  اگر دو گزینه متنِ یکسان داشته باشند، متن دیگر یکتا نیست. */
  correct: number
  /** پس از پاسخ درست، این توضیحِ کلی هم نشان داده می‌شود */
  because: string
}

export interface PredictQuestion extends BaseQuestion {
  kind: 'predict'
  question: string
  /** قطعه‌کدی که باید خروجی‌اش را پیش‌بینی کند.
   *
   *  اختیاری است، چون بعضی پیش‌بینی‌ها **کد ندارند**: مثلاً «کدام‌یک از این
   *  دو تصمیمِ معماری درست است؟» که جوابش یک جمله است نه خروجیِ یک برنامه.
   *  کامپوننت فقط وقتی این را دارد، بلوکِ کد را رسم می‌کند. */
  code?: string
  /** زبان برای رنگ‌آمیزی — فقط وقتی `code` هست لازم است */
  lang?: string
  /** ⭐ خروجیِ واقعی و درست */
  output: string
  /** چرا این خروجی درست است — نه اینکه چرا کد این‌طور کار می‌کند */
  why: string
  /** ⭐ فقط گزینه‌های **غلط**. یعنی «دام‌ها»: پیش‌بینی‌های رایجِ
   *  اشتباه، هرکدام با توضیحِ اینکه چرا ذهن به آن‌جا می‌رود.
   *
   *  ⚠️ عمداً گزینهٔ درست در همین آرایه **نیست**. کامپوننت خودش آن را از
   *  `output` به ابتدای فهرست اضافه می‌کند. اگر درست را دستی در آرایه
   *  می‌گذاشتیم، یک جابه‌جاییِ ساده در ویرایش بعدی کل پرسش را غلط می‌کرد
   *  و هیچ‌جا خطا نمی‌داد. */
  traps: Choice[]
}

export interface ExerciseV2 extends BaseQuestion {
  kind: 'exercise'
  question: string
  /** داده‌ای که کاربر باید رویش کار کند (نمونهٔ ساختگی) */
  data?: {
    name: string
    columns: string[]
    rows: string[][]
  }
  /** راهنمای مرحله‌به‌مرحله، فقط بعد از درخواست کاربر */
  steps: string[]
  /** ⭐ جوابِ حل‌شده. در نسخهٔ ۱ هرگز نشان داده نمی‌شد — کاربر نمی‌توانست
   *  خودش را بررسی کند. این مهم‌ترین افزودهٔ آموزشیِ نسخهٔ ۲ است. */
  solution: string
  /** خروجیِ نهاییِ حل (جدول یا متن) تا بتوان مقایسه کرد */
  answerData?: {
    name: string
    columns: string[]
    rows: string[][]
  }
}

export type Question = ChoiceQuestion | PredictQuestion | ExerciseV2

/** محتوایِ تعاملیِ یک فاز. */
export interface InteractiveContent {
  /** شمارهٔ فاز؛ برای تطبیق با نامِ فایل */
  num: number
  questions: Question[]
}

/** نتیجهٔ پاسخِ کاربر — برای ذخیره در localStorage. */
export interface AnswerRecord {
  /** گزینهٔ انتخابیِ کاربر (برای پرسشِ انتخابی و پیش‌بینی) */
  chosen?: number
  /** آیا کاربر جواب را دیده است */
  revealed: boolean
  /** آیا درست جواب داده است */
  correct: boolean
  /** چند بار تلاش کرده */
  tries: number
}